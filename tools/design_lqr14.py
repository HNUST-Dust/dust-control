#!/usr/bin/env python3
"""由显式十四状态动力学离线生成 1 kHz 离散 LQR；不内置机器人参数。"""
import argparse
import json
from pathlib import Path

import numpy as np
from scipy.linalg import expm, solve_discrete_are

STATES = ["position", "speed", "yaw", "yaw_rate", "left_theta",
          "left_theta_rate", "right_theta", "right_theta_rate", "pitch",
          "pitch_rate", "roll", "roll_rate", "height", "height_rate"]
INPUTS = ["left_wheel_torque", "right_wheel_torque", "left_body_on_leg_torque",
          "right_body_on_leg_torque", "left_vertical_force", "right_vertical_force"]
SAMPLE_TIME = 0.001


def matrix(data, name, shape):
    value = np.asarray(data[name], dtype=float)
    if value.shape != shape or not np.isfinite(value).all():
        raise ValueError(f"{name} must be finite with shape {shape}")
    return value


def synthesize(data):
    if data.get("state_order") != STATES or data.get("input_order") != INPUTS:
        raise ValueError("state_order/input_order do not match LQR14 coordinates")
    if data.get("contact_mode") != "double_support":
        raise ValueError("this design requires explicit double_support mode")
    if data.get("input_convention") != "physical_torques_upward_vertical_forces":
        raise ValueError("input convention must use physical torques and upward forces")
    if not isinstance(data.get("model_source"), str) or not data["model_source"].strip():
        raise ValueError("model_source is required for provenance")
    if not isinstance(data.get("height_definition"), str) or not data["height_definition"].strip():
        raise ValueError("height_definition must identify the body point and ground datum")
    operating_state = matrix(data, "operating_state", (14,))
    operating_input = matrix(data, "operating_input", (6,))
    if np.min(operating_input[4:]) < 0:
        raise ValueError("operating vertical forces must be nonnegative")
    dt = float(data["sample_time_s"])
    if not np.isfinite(dt) or abs(dt - SAMPLE_TIME) > 1e-12:
        raise ValueError("LQR14 requires sample_time_s=0.001")
    a = matrix(data, "A", (14, 14))
    b = matrix(data, "B", (14, 6))
    q = matrix(data, "Q", (14, 14))
    r = matrix(data, "R", (6, 6))
    for name, weight in (("Q", q), ("R", r)):
        if not np.allclose(weight, weight.T, atol=1e-12, rtol=1e-12):
            raise ValueError(f"{name} must be symmetric")
    if np.linalg.eigvalsh(q).min() < -1e-12 or np.linalg.eigvalsh(r).min() <= 0:
        raise ValueError("Q must be positive semidefinite and R positive definite")
    # Q/R 为每采样步离散代价；连续动力学采用精确零阶保持离散化。
    if data.get("time_domain") == "continuous":
        augmented = np.zeros((20, 20))
        augmented[:14, :14] = a
        augmented[:14, 14:] = b
        discrete = expm(augmented * dt)
        a, b = discrete[:14, :14], discrete[:14, 14:]
    elif data.get("time_domain") != "discrete":
        raise ValueError("time_domain must be continuous or discrete")
    p = solve_discrete_are(a, b, q, r)
    k = np.linalg.solve(r + b.T @ p @ b, b.T @ p @ a)
    residual = a.T @ p @ a - p - a.T @ p @ b @ k + q
    relative_residual = np.linalg.norm(residual) / max(1.0, np.linalg.norm(p))
    radius = float(np.max(np.abs(np.linalg.eigvals(a - b @ k))))
    if not np.isfinite(k).all() or not np.isfinite(relative_residual) or \
            relative_residual > 1e-8 or not radius < 1.0:
        raise ValueError("Riccati residual or closed-loop stability check failed")
    return {"sample_time_s": dt, "state_order": STATES, "input_order": INPUTS,
            "height_definition": data["height_definition"],
            "operating_state": operating_state.tolist(),
            "operating_input": operating_input.tolist(),
            "model_source": data["model_source"],
            "contact_mode": data["contact_mode"],
            "input_convention": data["input_convention"],
            "gain": k.tolist(), "discrete_a": a.tolist(), "discrete_b": b.tolist(),
            "riccati_p": p.tolist(), "relative_dare_residual": float(relative_residual),
            "closed_loop_spectral_radius": radius}


def cpp_header(result):
    # 固定函数名，不把外部模型描述插入 C++ 源码。
    rows = [", ".join(format(x, ".17g") for x in row) for row in result["gain"]]
    return """// Generated by tools/design_lqr14.py; see companion JSON for model provenance.
#pragma once
#include "chassis/balance/unified_lqr14.h"

namespace dust_control::chassis {
inline UnifiedLqr14::Design MakeLqr14Design() {
    UnifiedLqr14::Design design;
    design.gain <<
        """ + ",\n        ".join(rows) + ";\n    return design;\n}\n}  // namespace dust_control::chassis\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("model", type=Path, help="explicit A/B/Q/R and coordinate metadata JSON")
    parser.add_argument("--output", type=Path, required=True, help="design/diagnostic JSON")
    parser.add_argument("--header", type=Path, help="optional C++ gain header")
    args = parser.parse_args()
    result = synthesize(json.loads(args.model.read_text()))
    args.output.write_text(json.dumps(result, indent=2, allow_nan=False) + "\n")
    if args.header:
        args.header.write_text(cpp_header(result))
    print(f"closed-loop spectral radius: {result['closed_loop_spectral_radius']:.9f}")
    print(f"relative DARE residual: {result['relative_dare_residual']:.3g}")


if __name__ == "__main__":
    main()
