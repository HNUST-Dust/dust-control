#!/usr/bin/env python3
"""Generate DTG1 layout constants from the build-time YAML schema."""
import argparse
from pathlib import Path
import yaml


def generate(schema, output):
    data = yaml.safe_load(Path(schema).read_text())
    if set(data) != {"protocol", "layout_version", "signature", "cycle_time_us",
                     "record_bytes", "payload_bytes", "rx", "tx", "regions", "hi91", "routes", "startup_values"}:
        raise ValueError("Unexpected or missing DTG1 schema key")
    if data["protocol"] != "dtg1" or data["cycle_time_us"] != 125:
        raise ValueError("Only the DTG1 125 us protocol is supported")
    if data["record_bytes"] != 10 or data["payload_bytes"] != 8:
        raise ValueError("DTG1 motor records require 10 bytes and 8 payload bytes")
    lines = ["// Generated by tools/generate_pdo_schema.py; do not edit.",
             "#pragma once", "#include <array>", "#include <cstdint>",
             "namespace dust_control::ethercat::pdo {"]
    def constant(name, value):
        if type(value) is not int or value < 0 or value > 0xffffffff:
            raise ValueError(f"Invalid {name}")
        lines.append(f"inline constexpr uint32_t {name} = {value}U;")
    for key, name in (("layout_version", "kLayoutVersion"), ("signature", "kSignature"),
                      ("cycle_time_us", "kCycleTimeUs"), ("record_bytes", "kRecordBytes"),
                      ("payload_bytes", "kPayloadBytes")):
        constant(name, data[key])
    lines.append("struct Entry { uint16_t object; uint8_t subindex; uint8_t bits; uint32_t offset; };")
    sizes = {}
    for direction, prefix in (("rx", "Rx"), ("tx", "Tx")):
        image = data[direction]
        if set(image) != {"mapping", "object", "entries"}:
            raise ValueError(f"Invalid {direction} mapping")
        if not all(type(image[k]) is int and 0 < image[k] <= 65535 for k in ("mapping", "object")):
            raise ValueError("Invalid PDO object index")
        bits = image["entries"]
        if not isinstance(bits, list) or not 1 <= len(bits) <= 255:
            raise ValueError("Invalid PDO entry count")
        if any(type(value) is not int or value <= 0 or value > 240 or value % 8 for value in bits):
            raise ValueError("PDO entries must be byte aligned and at most 240 bits")
        offset = 0
        entries = []
        for index, value in enumerate(bits, 1):
            entries.append(f"    {{{image['object']}, {index}, {value}, {offset}}},")
            offset += value // 8
        sizes[direction] = offset
        constant(f"k{prefix}Mapping", image["mapping"])
        constant(f"k{prefix}Bytes", offset)
        lines += [f"inline constexpr std::array<Entry, {len(bits)}> k{prefix}Entries{{{{", *entries, "}};"]
    if sizes != {"rx": 60, "tx": 180}:
        raise ValueError("DTG1 requires 60-byte RxPDO and 180-byte TxPDO")
    regions = data["regions"]
    if set(regions) != {"motors", "onboard_imu", "hi91"}:
        raise ValueError("Missing DTG1 sensor region")
    previous_end = 0
    for key, name in (("motors", "Motors"), ("onboard_imu", "OnboardImu"), ("hi91", "Hi91")):
        region = regions[key]
        if set(region) != {"offset", "bytes"}:
            raise ValueError("Invalid region")
        start, size = region["offset"], region["bytes"]
        if type(start) is not int or type(size) is not int or start < previous_end or size <= 0 or start + size > sizes["tx"]:
            raise ValueError("Overlapping or out-of-bounds sensor region")
        constant(f"k{name}Offset", start)
        constant(f"k{name}Bytes", size)
        previous_end = start + size
    if regions["motors"] != {"offset": 0, "bytes": 60} or regions["onboard_imu"]["bytes"] != 28 or regions["hi91"]["bytes"] != 60:
        raise ValueError("Invalid DTG1 sensor region sizes")
    hi91 = data["hi91"]
    if set(hi91) != {"page_type", "fields_offset", "fields_bytes"} or hi91["fields_bytes"] != 52 or hi91["fields_offset"] < 5 or hi91["fields_offset"] + hi91["fields_bytes"] > regions["hi91"]["bytes"]:
        raise ValueError("Invalid compact HI91 fields")
    for key, name in (("page_type", "kHi91PageType"), ("fields_offset", "kHi91FieldsOffset"), ("fields_bytes", "kHi91FieldsBytes")):
        constant(name, hi91[key])
    routes = data["routes"]
    if len(routes) != 6:
        raise ValueError("DTG1 requires six motor routes")
    seen = set()
    lines += ["struct CanRoute { uint8_t bus; uint16_t command; uint16_t feedback; };",
              "inline constexpr std::array<CanRoute, 6> kRoutes{{"]
    for route in routes:
        if set(route) != {"bus", "command", "feedback"} or route["bus"] not in (0, 3) or any(type(route[k]) is not int or not 0 <= route[k] <= 0x7ff for k in ("command", "feedback")):
            raise ValueError("Invalid motor route")
        key = route["bus"], route["command"]
        if key in seen:
            raise ValueError("Duplicate motor command route")
        seen.add(key)
        lines.append(f"    {{{route['bus']}, {route['command']}, {route['feedback']}}},")
    lines.append("}};")
    startup = data["startup_values"]
    if not isinstance(startup, list) or len(startup) != 19 or any(type(value) is not int or not 0 <= value <= 0xffffffff for value in startup):
        raise ValueError("Invalid DTG1 startup SDO values")
    lines.append("inline constexpr std::array<uint32_t, 19> kStartupValues{" + ", ".join(str(value) + "U" for value in startup) + "};")
    lines += ["}  // namespace dust_control::ethercat::pdo", ""]
    Path(output).parent.mkdir(parents=True, exist_ok=True)
    Path(output).write_text("\n".join(lines))


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--schema", required=True)
    parser.add_argument("--output", required=True)
    args = parser.parse_args()
    generate(args.schema, args.output)
